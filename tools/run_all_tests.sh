#!/bin/bash
# THE pre-commit gate (CLAUDE.md "Robustness rules"). Runs every suite in tests/ ONE AT A TIME and
# fails if ANY suite exits non-zero OR prints a SCRIPT ERROR / Parse Error, or docs/blueprints/ is stale — a suite can report
# "ALL PASSED" while a check silently errored out (merchant_smoke_test called a renamed method and
# its check "passed" without running). Usage:
#   tools/run_all_tests.sh              # every suite
#   tools/run_all_tests.sh fire loot    # only suites whose name contains one of the words
# Logs go to $TEST_LOG_DIR (default /tmp/df30_tests). Exit 0 only when everything is clean.
cd "$(dirname "$0")/.." || exit 2
LOG_DIR="${TEST_LOG_DIR:-/tmp/df30_tests}"
mkdir -p "$LOG_DIR"
if pgrep -x godot >/dev/null; then
	echo "A headless godot is already running — stop it first (suites must run one at a time)." >&2
	exit 2
fi
godot --headless --import >"$LOG_DIR/_import.log" 2>&1 || { echo "IMPORT FAILED (see $LOG_DIR/_import.log)"; exit 1; }
bad=0
count=0
# The LOCKED room-module blueprints (docs/blueprints/, the artists' template) must match the rooms as
# built — regenerated in memory, compared pixel for pixel, and no back-plane spot may be blocked.
if python3 tools/gen_module_blueprint.py --check >"$LOG_DIR/_blueprints.log" 2>&1; then
	echo "ok     blueprints (docs/blueprints current)"
else
	echo "FAIL   blueprints — run: python3 tools/gen_module_blueprint.py"; grep "BLUEPRINTS:" "$LOG_DIR/_blueprints.log" | head -5
	bad=$((bad + 1))
fi
# The opened-furniture patches (assets/rooms/open/) are baked from the finished module art — stale = wrong picture.
if python3 tools/art/openables.py --check >"$LOG_DIR/_openables.log" 2>&1; then
	echo "ok     openables (assets/rooms/open current)"
else
	echo "FAIL   openables — run: python3 tools/art/build_all.py && python3 tools/art/openables.py"; grep "OPENABLES:" "$LOG_DIR/_openables.log" | head -3
	bad=$((bad + 1))
fi
# The burnt-out module art (assets/rooms/*_burnt*.png) is baked from the finished run-3 art — stale = the wrong room.
if python3 tools/art/burnt.py --check >"$LOG_DIR/_burnt.log" 2>&1; then
	echo "ok     burnt art (assets/rooms/*_burnt* current)"
else
	echo "FAIL   burnt art — run: python3 tools/art/build_all.py && python3 tools/art/burnt.py"; grep "BURNT:" "$LOG_DIR/_burnt.log" | head -3
	bad=$((bad + 1))
fi
# The new-game opening's exterior layers (assets/opening/) are generated by tools/art/opening.py — stale = the wrong picture.
if python3 tools/art/opening.py --check >"$LOG_DIR/_opening.log" 2>&1; then
	echo "ok     opening art (assets/opening current)"
else
	echo "FAIL   opening art — run: python3 tools/art/opening.py"; head -3 "$LOG_DIR/_opening.log"
	bad=$((bad + 1))
fi
# Vivianne's cat sprite strips (assets/cat/) are generated by tools/art/cat.py — stale = the wrong picture.
if python3 tools/art/cat.py --check >"$LOG_DIR/_cat.log" 2>&1; then
	echo "ok     cat art (assets/cat current)"
else
	echo "FAIL   cat art — run: python3 tools/art/cat.py"; head -3 "$LOG_DIR/_cat.log"
	bad=$((bad + 1))
fi
# The corridor's paper (notices, flyers, the kid's drawing — assets/corridor/decals/) and every room poster / frame come
# from tools/art/wallart.py: a stale decal PNG, a piece over the notice slot, or a helper that has gone missing fails here.
if python3 tools/art/wallart.py --check >"$LOG_DIR/_wallart.log" 2>&1; then
	echo "ok     wall art (corridor paper current, room pieces draw)"
else
	echo "FAIL   wall art — run: python3 tools/art/corridor_decals.py"; head -5 "$LOG_DIR/_wallart.log"
	bad=$((bad + 1))
fi
# FURNITURE AS ASSETS (owner round 47): the sprites in assets/furniture/ + data/furniture.json (every piece, its rooms / styles / tags / slots / nodes, the room recipes) are generated by
# tools/art/furn_build.py and the bare bedroom shells by tools/art/furn_shells.py — a stale file, a missing sprite or an orphan fails here. (tests/furniture_test.gd proves the logic itself.)
if python3 tools/art/furn_build.py --check >"$LOG_DIR/_furniture.log" 2>&1 && python3 tools/art/furn_shells.py --check >>"$LOG_DIR/_furniture.log" 2>&1; then
	echo "ok     furniture library ($(grep -h -E '^(FURNITURE|SHELLS):' "$LOG_DIR/_furniture.log" | tr '\n' ' '))"
else
	echo "FAIL   furniture library — run: python3 tools/art/furn_build.py && python3 tools/art/furn_shells.py"; grep -E "FURNITURE:|SHELLS:|Error|error" "$LOG_DIR/_furniture.log" | head -5
	bad=$((bad + 1))
fi
# COLOUR HARMONY (owner round 47h: "too garish against modules… colour matchups need to look appropriate and appealing"): no shell wall / floor is loud, and no large piece has a colourway that
# blends into the wall or floor of a style it stands in (tools/art/colour_audit.py --check; the exceptions are listed in tools/art/furn_palette.py AVOID).
if python3 tools/art/colour_audit.py --check >"$LOG_DIR/_colour.log" 2>&1; then
	echo "ok     colour harmony ($(tail -1 "$LOG_DIR/_colour.log" | sed 's/^COLOUR: //'))"
else
	echo "FAIL   colour harmony — see tools/art/colour_audit.py and tools/art/furn_palette.py"; head -6 "$LOG_DIR/_colour.log"
	bad=$((bad + 1))
fi
# Every sound must stay clean (owner round 46: "a lot of what feels like static and noise in the audio"): no hiss / fizz above the budgets in
# tools/audio_audit.py, no clipping or DC offset, no tick at a loop's join, no music that is all sub. Decodes every file in assets/audio.
if python3 tools/audio_audit.py --check >"$LOG_DIR/_audio.log" 2>&1; then
	echo "ok     audio quality ($(tail -1 "$LOG_DIR/_audio.log" | sed 's/^AUDIO: //'))"
else
	echo "FAIL   audio quality — see tools/audio_audit.py; regenerate with tools/gen_*audio.py / tools/gen_music.py / tools/audio_clean.py"; grep "AUDIO:" "$LOG_DIR/_audio.log" | head -8
	bad=$((bad + 1))
fi
for t in tests/*.tscn; do
	n=$(basename "$t" .tscn)
	if [ $# -gt 0 ]; then
		hit=0
		for w in "$@"; do [[ "$n" == *"$w"* ]] && hit=1; done
		[ $hit -eq 0 ] && continue
	fi
	count=$((count + 1))
	log="$LOG_DIR/$n.log"
	timeout 300 godot --headless "res://$t" >"$log" 2>&1
	code=$?
	if [ $code -ne 0 ]; then
		echo "FAIL   $n (exit $code)"; grep -E "  FAIL " "$log" | head -5
		bad=$((bad + 1))
	elif grep -qE "SCRIPT ERROR|Parse Error" "$log"; then
		echo "ERROR  $n (passed, but a script error fired — a check may not have run)"
		grep -E -A2 "SCRIPT ERROR|Parse Error" "$log" | head -6
		bad=$((bad + 1))
	else
		echo "ok     $n"
	fi
done
echo "---- $count suites, $bad bad ----"
[ $bad -eq 0 ]
