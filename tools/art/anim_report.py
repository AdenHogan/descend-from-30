#!/usr/bin/env python3
"""THE ANIMATION CHECK (owner 2026-11-25: "check the animations… separate the images into a sprite sheet for each animation type").

Reads the strips ON DISK (assets/players/<name>/<key>.png, assets/monsters/<kind>/<Anim>.png — so a strip that has been redrawn by hand is checked too) and the SpriteFrames written beside
them, and writes docs/ANIMATIONS.md plus labelled contact sheets in docs/art_reference/animation_check/. Checked per strip: the frame count against the cell, every frame non-empty, nothing
touching a cell's edge (clipped), where the feet land, the fps / duration / loop the game will play it at, and how far the whole figure drifts frame to frame.

    python3 tools/art/anim_report.py
"""
import json
import os
import re

from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
PL = os.path.join(ROOT, 'assets', 'players')
MO = os.path.join(ROOT, 'assets', 'monsters')
OUT = os.path.join(ROOT, 'docs', 'art_reference', 'animation_check')


def frames_of(path, cell):
    im = Image.open(path).convert('RGBA')
    n = max(1, im.width // cell[0])
    return [im.crop((i * cell[0], 0, (i + 1) * cell[0], cell[1])) for i in range(n)]


def stats(frs):
    issues = []
    boxes = []
    for i, f in enumerate(frs):
        b = f.getbbox()
        if b is None:
            issues.append('frame %d is empty' % i)
            boxes.append(None)
            continue
        boxes.append(b)
        px = f.load()
        w, h = f.size
        if any(px[x, 0][3] for x in range(w)) or any(px[0, y][3] or px[w - 1, y][3] for y in range(h)):
            issues.append('frame %d touches the cell edge (clipped)' % i)
    good = [b for b in boxes if b]
    return boxes, good, issues


def read_tres(path):
    """{animation name: (frames, fps, loop)} from a SpriteFrames .tres (as the generators write it)."""
    txt = open(path).read()
    out = {}
    for m in re.finditer(r'\{\s*"frames": \[(.*?)\],\s*"loop": (\w+),\s*"name": &"([^"]+)",\s*"speed": ([\d.]+)', txt, re.S):
        out[m.group(3)] = (m.group(1).count('SubResource'), float(m.group(4)), m.group(2) == 'true')
    return out


def sheet_for(label_rows, cell, title, path, scale=1):
    w = max(len(frs) for _, frs in label_rows) * cell[0] + 150
    h = len(label_rows) * (cell[1] + 6) + 22
    sh = Image.new('RGBA', (w, h), (52, 54, 64, 255))
    d = ImageDraw.Draw(sh)
    d.text((6, 4), title, fill=(230, 230, 236, 255))
    y = 22
    for name, frs in label_rows:
        d.text((6, y + cell[1] // 2 - 5), name, fill=(200, 205, 214, 255))
        for i, f in enumerate(frs):
            sh.alpha_composite(f, (150 + i * cell[0], y))
            d.line([(150 + i * cell[0], y + cell[1] - 1), (150 + (i + 1) * cell[0] - 1, y + cell[1] - 1)], fill=(90, 96, 110, 255))     # the floor line of each cell
        y += cell[1] + 6
    if scale != 1:
        sh = sh.resize((sh.width * scale, sh.height * scale), Image.NEAREST)
    sh.save(path)


def main():
    os.makedirs(OUT, exist_ok=True)
    md = ['# Animations — what exists, as strips on disk (GENERATED by `tools/art/anim_report.py`; do not hand-edit)\n',
          'Every animation is its OWN PNG strip: the frames left to right in equal cells, so any one can be redrawn by hand. The generators (`tools/art/player_rigs.py`, `tools/art/creatures.py`)',
          'write a strip only when it is missing (a redrawn one is safe) unless run with `--regen`; the frame count is read from the file, and the `.tres` SpriteFrames beside them points at the strips.',
          'Contact sheets (all strips of a character stacked, a floor line under each cell): `docs/art_reference/animation_check/`.\n']
    problems = 0
    pj = json.load(open(os.path.join(PL, 'players.json')))
    cell = tuple(pj['cell'])
    md.append('## The four players — strips at `assets/players/<name>/<key>.png`, cell %d x %d (the feet on the bottom row, the hips on the middle column)\n' % cell)
    md.append('| key | frames | fps | cycle s | loop | figure h px | feet row | drift | check |')
    md.append('|---|---|---|---|---|---|---|---|---|')
    tres = read_tres(os.path.join(PL, 'joe_frames.tres'))
    inv = {}
    for an, key in pj['alias'].items():
        inv.setdefault(key, []).append(an)
    for who in ('joe', 'vivianne', 'alex', 'amina'):
        rows = []
        for key in pj['players'][who]['files']:
            frs = frames_of(os.path.join(PL, who, key + '.png'), cell)
            rows.append((key, frs))
            boxes, good, issues = stats(frs)
            if who == 'joe':
                an = inv.get(key, [key])[0]
                n, fps, loop = tres.get(an, (len(frs), 0.0, True))
                feet = sorted({b[3] for b in good})
                hs = [b[3] - b[1] for b in good]
                cx = [(b[0] + b[2]) / 2.0 for b in good]
                drift = max(cx) - min(cx) if cx else 0.0
                bad = ['file has %d frames, the game plays %d' % (len(frs), n)] if n != len(frs) else []
                md.append('| `%s` | %d | %.1f | %.2f | %s | %d-%d | %s | %.0f | %s |' % (key, len(frs), fps, len(frs) / fps if fps else 0.0, 'yes' if loop else 'no', min(hs), max(hs),
                          '%d' % feet[0] if len(feet) == 1 else '%d-%d' % (feet[0], feet[-1]), drift, '; '.join(issues + bad) or 'ok'))
            else:
                if issues:
                    md.append('\n%s `%s`: %s' % (who, key, '; '.join(issues)))
            problems += len(issues)
        sheet_for(rows, cell, '%s — every animation' % who, os.path.join(OUT, 'player_%s.png' % who))
    md.append('\nThe game plays these NAMES (`animated_sprite.play(name)`); several names share a strip until they get their own:\n')
    md.append('| the game plays | strip | |')
    md.append('|---|---|---|')
    placeholder = {'katana_idle', 'sword_idle', 'grab'}
    for an, key in pj['alias'].items():
        md.append('| `%s` | `%s` | %s |' % (an, key, 'PLACEHOLDER: uses the idle pose (no own drawing yet)' if an in placeholder else ('shares the walk / run legs' if key in ('walk', 'run') and an != key else '')))
    md.append('\nNOT built for the players yet (the game falls back to the nearest pose): kneeling to open the pack, the stairs, climbing, the torch held out, throwing, a portrait mood change.\n')
    mj = json.load(open(os.path.join(MO, 'monsters.json')))
    md.append('## The monsters — strips at `assets/monsters/<kind>/<Anim>.png`\n')
    md.append('| kind | anim | frames | cell | fps | loop | feet row | check |')
    md.append('|---|---|---|---|---|---|---|---|')
    for kind, info in mj.items():
        mcell = tuple(info['cell'])
        t = read_tres(os.path.join(MO, kind + '_frames.tres'))
        rows = []
        for an in info['files']:
            frs = frames_of(os.path.join(MO, kind, an + '.png'), mcell)
            rows.append((an, frs))
            boxes, good, issues = stats(frs)
            n, fps, loop = t.get(an, (len(frs), 0.0, True))
            feet = sorted({b[3] for b in good})
            bad = ['file has %d frames, the game plays %d' % (len(frs), n)] if n != len(frs) else []
            md.append('| %s | %s | %d | %dx%d | %.0f | %s | %s | %s |' % (kind, an, len(frs), mcell[0], mcell[1], fps, 'yes' if loop else 'no', ('%d' % feet[0]) if len(feet) == 1 else ('%d-%d' % (feet[0], feet[-1])) if feet else '-',
                      '; '.join(issues + bad) or 'ok'))
            problems += len(issues) + len(bad)
        sheet_for(rows, mcell, '%s — every animation' % kind, os.path.join(OUT, 'monster_%s.png' % kind))
    open(os.path.join(ROOT, 'docs', 'ANIMATIONS.md'), 'w').write('\n'.join(md) + '\n')
    print('wrote docs/ANIMATIONS.md; problems:', problems)
    return problems


if __name__ == '__main__':
    main()
